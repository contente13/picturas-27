"""RNF-FIAB-01 deterministic corpus and reference outputs.

    python corpus.py generate   # write data/corpus/*.png and the manifest
    python corpus.py verify     # regenerate in memory and compare with the manifest

Ten 640x480 RGB PNG images (gradients, shapes and seeded noise) plus one file
with PNG extension that is not an image (R8). Only the manifest is versioned;
images are regenerated byte for byte with the pinned Pillow version.

The reference output of the pipeline border -> brightness -> rotate is computed
here with the same PIL operations as Tools/border, Tools/brightness and
Tools/rotate, and stored as a pixel hash (RGBA, independent of PNG encoder).
"""
import hashlib
import io
import json
import os
import random
import sys

import PIL
from PIL import Image, ImageDraw, ImageEnhance, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
DATA = os.path.join(HERE, "data", "corpus")
MANIFEST = os.path.join(REPO, "docs", "rnf-fiab-01", "evidencias", "corpus-manifest.json")

SEED = 20261114
COUNT = 10
SIZE = (640, 480)
INVALID_NAME = "img11-invalid.png"

PIPELINE = [
    {"procedure": "border", "params": {"borderWidth": 12, "r": 200, "g": 30, "b": 30}},
    {"procedure": "brightness", "params": {"brightness": 1.4}},
    {"procedure": "rotate", "params": {"degrees": 90}},
]


def image_name(i):
    return f"img{i:02d}.png"


def make_image(i):
    rng = random.Random(SEED + i)
    img = Image.new("RGB", SIZE)
    draw = ImageDraw.Draw(img)
    a = [rng.randrange(256) for _ in range(3)]
    b = [rng.randrange(256) for _ in range(3)]
    for y in range(SIZE[1]):
        t = y / (SIZE[1] - 1)
        draw.line([(0, y), (SIZE[0], y)], fill=tuple(int(a[c] + (b[c] - a[c]) * t) for c in range(3)))
    for _ in range(12):
        x0, y0 = rng.randrange(SIZE[0]), rng.randrange(SIZE[1])
        x1, y1 = x0 + rng.randrange(20, 200), y0 + rng.randrange(20, 160)
        color = tuple(rng.randrange(256) for _ in range(3))
        (draw.ellipse if rng.random() < 0.5 else draw.rectangle)([x0, y0, x1, y1], fill=color)
    noise = bytes(rng.randrange(256) for _ in range(160 * 120 * 3))
    img.paste(Image.frombytes("RGB", (160, 120), noise), (rng.randrange(480), rng.randrange(360)))
    return img


def png_bytes(img):
    buffer = io.BytesIO()
    img.save(buffer, format="PNG")
    return buffer.getvalue()


def pixel_sha256(img):
    rgba = img.convert("RGBA")
    return hashlib.sha256(f"{rgba.size[0]}x{rgba.size[1]}:".encode() + rgba.tobytes()).hexdigest()


def apply_pipeline(img):
    """Same operations as the image workers (see module docstring)."""
    p = PIPELINE
    img = ImageOps.expand(img, border=p[0]["params"]["borderWidth"],
                          fill=(p[0]["params"]["r"], p[0]["params"]["g"], p[0]["params"]["b"]))
    img = ImageEnhance.Brightness(img).enhance(p[1]["params"]["brightness"])
    return img.rotate(p[2]["params"]["degrees"], expand=True)


def invalid_bytes():
    rng = random.Random(SEED - 1)
    return b"NOT-AN-IMAGE RNF-FIAB-01\n" + bytes(rng.randrange(256) for _ in range(4096))


def build():
    files, entries = {}, []
    for i in range(1, COUNT + 1):
        img = make_image(i)
        data = png_bytes(img)
        decoded = Image.open(io.BytesIO(data))
        expected = apply_pipeline(decoded.convert("RGB"))
        files[image_name(i)] = data
        entries.append({
            "name": image_name(i), "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "pixel_sha256": pixel_sha256(decoded),
            "width": decoded.size[0], "height": decoded.size[1],
            "expected_pixel_sha256": pixel_sha256(expected),
            "expected_width": expected.size[0], "expected_height": expected.size[1],
        })
    bad = invalid_bytes()
    files[INVALID_NAME] = bad
    manifest = {
        "requirement": "RNF-FIAB-01",
        "generator": "tests/rnf-fiab-01/corpus.py",
        "seed": SEED, "pillow": PIL.__version__,
        "pipeline": PIPELINE,
        "images": entries,
        "invalid": {"name": INVALID_NAME, "bytes": len(bad), "sha256": hashlib.sha256(bad).hexdigest()},
    }
    return files, manifest


def generate():
    files, manifest = build()
    os.makedirs(DATA, exist_ok=True)
    for name, data in files.items():
        with open(os.path.join(DATA, name), "wb") as handle:
            handle.write(data)
    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    with open(MANIFEST, "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=2)
        handle.write("\n")
    print(f"wrote {len(files)} files to {DATA} and {MANIFEST}")


def verify():
    _, fresh = build()
    with open(MANIFEST, encoding="utf-8") as handle:
        saved = json.load(handle)
    if fresh != saved:
        sys.exit("corpus differs from manifest (check the Pillow version: manifest "
                 f"{saved.get('pillow')}, installed {PIL.__version__})")
    for entry in saved["images"] + [saved["invalid"]]:
        path = os.path.join(DATA, entry["name"])
        with open(path, "rb") as handle:
            if hashlib.sha256(handle.read()).hexdigest() != entry["sha256"]:
                sys.exit(f"{path} does not match the manifest; run: python corpus.py generate")
    print("corpus matches manifest")


def load_manifest():
    with open(MANIFEST, encoding="utf-8") as handle:
        return json.load(handle)


if __name__ == "__main__":
    {"generate": generate, "verify": verify}[sys.argv[1] if len(sys.argv) > 1 else "verify"]()
